#!/usr/bin/env python3
"""Copy rftools.io's design tokens and logo into the plugin's page.

    plugins/rftools_kicad/ui/tokens.css  the site's colour, type and shadow tokens
    plugins/rftools_kicad/ui/logo.svg    the logo mark and wordmark as SVG symbols

from the rfhub monorepo, which rftools-kicad sits in:

    frontend/src/styles/instrument.css                    [data-design="instrument"]
                                                          and its .dark block
    frontend/src/components/instrument/icons/LogoMark.tsx the mark
    frontend/src/components/instrument/icons/Wordmark.tsx the wordmark

Only custom properties are copied, with each value's whitespace collapsed to
single spaces. The light block becomes :root, the dark block becomes
[data-theme="dark"] and, under prefers-color-scheme: dark, [data-theme="auto"]
(the browser report). The fonts are committed beside them (ui/fonts/) and are
not regenerated here.

    python3 scripts/vendor_design.py           # rewrite the two files
    python3 scripts/vendor_design.py --check   # exit 1, naming what differs
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MONOREPO = ROOT.parent
SITE_CSS = MONOREPO / "frontend" / "src" / "styles" / "instrument.css"
ICONS = MONOREPO / "frontend" / "src" / "components" / "instrument" / "icons"
LOGOMARK = ICONS / "LogoMark.tsx"
WORDMARK = ICONS / "Wordmark.tsx"
UI = ROOT / "plugins" / "rftools_kicad" / "ui"

LIGHT_SELECTOR = '[data-design="instrument"]'
DARK_SELECTOR = '.dark [data-design="instrument"]'
#: The fonts the page inlines (committed, with OFL-*.txt beside them).
FONT_FILES = (
    "InstrumentSans-latin-wght.woff2",
    "IBMPlexMono-latin-400.woff2",
    "IBMPlexMono-latin-500.woff2",
    "IBMPlexMono-latin-600.woff2",
)
HEADER = (
    "/* Generated by scripts/vendor_design.py from frontend/src/styles/instrument.css."
    " Do not edit. */\n"
)


def _block(css: str, selector: str) -> str:
    """The body of the rule whose selector is exactly *selector* (first one)."""
    match = re.search(r"(?m)^" + re.escape(selector) + r"\s*\{", css)
    if not match:
        raise ValueError(f"no rule {selector!r} in the site's stylesheet")
    depth, i = 1, match.end()
    while depth:
        depth += {"{": 1, "}": -1}.get(css[i], 0)
        i += 1
    return css[match.end():i - 1]


def _declarations(body: str) -> dict:
    """Custom properties of a rule body, in order, whitespace collapsed."""
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    tokens = {}
    for part in body.split(";"):
        name, _, value = part.partition(":")
        name = name.strip()
        if name.startswith("--") and value.strip():
            tokens[name] = " ".join(value.split())
    return tokens


def _rule(selector: str, tokens: dict, indent: str = "") -> str:
    lines = [f"{indent}{selector} {{"]
    lines += [f"{indent}  {name}: {value};" for name, value in tokens.items()]
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def render_tokens(site_css: str) -> str:
    light = _declarations(_block(site_css, LIGHT_SELECTOR))
    dark = _declarations(_block(site_css, DARK_SELECTOR))
    return (
        HEADER
        + _rule(':root, [data-theme="light"]', light) + "\n"
        + _rule('[data-theme="dark"]', dark) + "\n"
        + "@media (prefers-color-scheme: dark) {\n"
        + _rule('[data-theme="auto"]', dark, indent="  ") + "\n}\n"
    )


def token_blocks_of(tokens_css: str) -> tuple:
    """(light, dark) custom properties of a generated tokens.css."""
    light = _declarations(_block(tokens_css, ':root, [data-theme="light"]'))
    dark = _declarations(_block(tokens_css, '[data-theme="dark"]'))
    return light, dark


def token_drift(committed: str, generated: str) -> list:
    """Names of the tokens whose value differs, in either theme, sorted."""
    names = set()
    for have, want in zip(token_blocks_of(committed), token_blocks_of(generated)):
        names |= {n for n in set(have) | set(want) if have.get(n) != want.get(n)}
    return sorted(names)


def _jsx_to_svg(markup: str) -> str:
    """LogoMark's JSX children as SVG: camelCase attributes in kebab case."""
    markup = re.sub(r"\s+", " ", markup).strip()
    return re.sub(
        r"\b(stroke|fill)([A-Z])(\w*)=", lambda m: f"{m[1]}-{m[2].lower()}{m[3]}=", markup
    )


def render_logo(logomark_tsx: str, wordmark_tsx: str) -> str:
    mark = re.search(r"<svg[^>]*>(.*?)</svg>", logomark_tsx, re.S)
    words = re.findall(r'<path\b([^>]*?)\bd="([^"]+)"', wordmark_tsx)
    if not mark or len(words) != 2:
        raise ValueError("LogoMark.tsx or Wordmark.tsx no longer has the expected shape")
    (first, first_d), (second, second_d) = words
    if 'fill="currentColor"' not in first or "var(--subtle)" not in second:
        raise ValueError("Wordmark.tsx's two paths changed their colours")
    return (
        '<svg aria-hidden="true" focusable="false" style="display:none">'
        f'<symbol id="rf-mark" viewBox="0 0 22 22">{_jsx_to_svg(mark.group(1))}</symbol>'
        '<symbol id="rf-wordmark" viewBox="0 0 66.45 19.52">'
        f'<path fill="currentColor" d="{first_d}"/>'
        f'<path style="fill:var(--subtle)" d="{second_d}"/>'
        "</symbol></svg>\n"
    )


def outputs() -> dict:
    return {
        UI / "tokens.css": render_tokens(SITE_CSS.read_text(encoding="utf-8")),
        UI / "logo.svg": render_logo(LOGOMARK.read_text(encoding="utf-8"),
                                     WORDMARK.read_text(encoding="utf-8")),
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare, do not write")
    args = parser.parse_args(argv)
    if not SITE_CSS.is_file():
        print(f"The monorepo's frontend is not beside {ROOT}; nothing to compare.", file=sys.stderr)
        return 2
    stale = []
    for path, text in outputs().items():
        if args.check:
            have = path.read_text(encoding="utf-8") if path.is_file() else ""
            if have != text:
                detail = ""
                if path.name == "tokens.css" and have:
                    detail = ": " + ", ".join(token_drift(have, text) or ["formatting"])
                stale.append(f"{path.relative_to(ROOT)}{detail}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Differs from the site: " + "; ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
